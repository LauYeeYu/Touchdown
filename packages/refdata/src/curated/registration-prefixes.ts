function escape(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export const registrationPrefixes: RegistrationPrefix[] = rows.map(([prefix, country, suffix]) => ({
  prefix,
  country,
  pattern: `^${escape(prefix)}${suffix}$`,
}));
